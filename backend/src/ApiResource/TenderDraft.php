<?php

namespace App\ApiResource;

use ApiPlatform\Metadata\ApiResource;
use ApiPlatform\Metadata\Post;
use App\Entity\Tender;
use App\State\AiProcessor;
use Symfony\Component\Serializer\Attribute\Groups;
use Symfony\Component\Validator\Constraints as Assert;

/**
 * AI agent: turns a short brief into a complete, structured call for tenders (not persisted).
 */
#[ApiResource(
    shortName: 'AiTenderDraft',
    operations: [
        new Post(
            uriTemplate: '/ai/tender-draft',
            status: 200,
            security: "is_granted('ROLE_BUYER') or is_granted('ROLE_REQUESTER')",
            processor: AiProcessor::class,
            openapi: new \ApiPlatform\OpenApi\Model\Operation(summary: 'Generate a tender description from a brief.'),
        ),
    ],
    normalizationContext: ['groups' => ['ai:read']],
    denormalizationContext: ['groups' => ['ai:write']],
)]
final class TenderDraft
{
    #[Assert\NotBlank]
    #[Assert\Length(min: 5, max: 200)]
    #[Groups(['ai:write', 'ai:read'])]
    public string $title = '';

    #[Assert\NotBlank]
    #[Assert\Length(min: 20, max: 5000)]
    #[Groups(['ai:write'])]
    public string $context = '';

    /** @var list<string> */
    #[Assert\All([new Assert\Type('string'), new Assert\Length(max: 60)])]
    #[Groups(['ai:write', 'ai:read'])]
    public array $skills = [];

    #[Assert\Choice(choices: Tender::SENIORITIES)]
    #[Groups(['ai:write', 'ai:read'])]
    public string $seniority = 'confirmed';

    #[Assert\Range(min: 1, max: 1000)]
    #[Groups(['ai:write', 'ai:read'])]
    public int $estimatedDays = 60;

    #[Groups(['ai:read'])]
    public ?string $description = null;

    /** @var array{low: int, median: int, high: int, sampleSize: int, basis: string, rationale: string, source: string}|null */
    #[Groups(['ai:read'])]
    public ?array $suggestedPrice = null;

    /** "llm" when generated by Claude, "template" for the deterministic fallback. */
    #[Groups(['ai:read'])]
    public string $source = 'template';
}
